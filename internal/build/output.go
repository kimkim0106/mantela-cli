package build

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// MarkLine is the header line put at the top of generated Asterisk files.
const MarkLine = "; generated by mantela-cli. DO NOT EDIT."

const hashPrefix = "; sha256:"

// WithMark prepends the generated-file header (the mark line and the sha256 of body) to body.
func WithMark(body string) []byte {
	sum := sha256.Sum256([]byte(body))
	return []byte(MarkLine + "\n" + hashPrefix + hex.EncodeToString(sum[:]) + "\n" + body)
}

// Error kinds, distinguishable with errors.Is.
var (
	ErrNotGenerated = errors.New("not generated by mantela-cli")
	ErrEdited       = errors.New("generated file has been edited by hand")
)

// CheckOverwrite checks whether a generated file may be written to path.
// It returns nil if the file does not exist, or has the header and a matching hash.
func CheckOverwrite(path string) error {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	mark, rest, _ := strings.Cut(string(data), "\n")
	if mark != MarkLine {
		return fmt.Errorf("%s: refusing to overwrite: %w (no generated-file header). Use a directory dedicated to mantela-cli as the output", path, ErrNotGenerated)
	}
	hashLine, body, _ := strings.Cut(rest, "\n")
	sum := sha256.Sum256([]byte(body))
	if hashLine != hashPrefix+hex.EncodeToString(sum[:]) {
		return fmt.Errorf("%s: refusing to overwrite: %w (sha256 in the header does not match the content). Move the changes into the station directory, delete this file, and build again", path, ErrEdited)
	}
	return nil
}

// WriteFile writes data to path, skipping the write if the content is unchanged.
// It writes a temporary file and renames it, so a failure never leaves a partial file.
func WriteFile(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name()) // no-op after a successful rename
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
