package build

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// MarkLine は、Asterisk 用の生成物の先頭に入れる印。
const MarkLine = "; generated by mantela-cli. DO NOT EDIT."

const hashPrefix = "; sha256:"

// WithMark は、本文の前に生成物の印（印の行と、本文の sha256 の行）を付ける。
func WithMark(body string) []byte {
	sum := sha256.Sum256([]byte(body))
	return []byte(MarkLine + "\n" + hashPrefix + hex.EncodeToString(sum[:]) + "\n" + body)
}

// エラーの種類。errors.Is で見分けられる。
var (
	ErrNotGenerated = errors.New("mantela-cli の生成物ではない")
	ErrEdited       = errors.New("生成物が手で編集されている")
)

// CheckOverwrite は、path に生成物を書いてよいかを確かめる。
// ファイルが無いか、印があって本文のハッシュが合えば nil を返す。
func CheckOverwrite(path string) error {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	mark, rest, _ := strings.Cut(string(data), "\n")
	if mark != MarkLine {
		return fmt.Errorf("%s: %w（先頭に印が無い）ので上書きしません。出力先には mantela-cli 専用のディレクトリを指定してください", path, ErrNotGenerated)
	}
	hashLine, body, _ := strings.Cut(rest, "\n")
	sum := sha256.Sum256([]byte(body))
	if hashLine != hashPrefix+hex.EncodeToString(sum[:]) {
		return fmt.Errorf("%s: %w（印のハッシュが本文と合わない）ので上書きしません。変更を局ディレクトリへ移してから、このファイルを消して build し直してください", path, ErrEdited)
	}
	return nil
}

// WriteFile は、data を path に書く。中身が同じなら書かない。
// 一時ファイルに書いてから置き換えるので、途中で失敗しても半端なファイルは残らない。
func WriteFile(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name()) // 置き換えに成功したら何もしない
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
